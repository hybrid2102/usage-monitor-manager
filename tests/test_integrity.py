"""Tests for the integrity checks: sha256, sidecar parsing, Authenticode.

The Authenticode tests are the only ones in the suite that read a real file
outside ``tmp_path``: ``C:\\Windows\\System32\\kernel32.dll`` is read-only and
signed with an embedded signature, which makes it the one dependable "signed"
sample on any Windows machine. Nothing is written, started or stopped.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

import pytest

from usage_monitor_manager.integrity import (
    IntegrityResult,
    authenticode_status,
    normalize_digest,
    parse_sidecar,
    sha256_file,
    verify_digest,
)

KERNEL32 = Path(r"C:\Windows\System32\kernel32.dll")


@pytest.fixture
def sample(tmp_path: Path) -> Path:
    path = tmp_path / "UsageMonitorForCopilot.exe.download"
    path.write_bytes(b"pretend this is 15 MB of PyInstaller" * 1000)
    return path


def test_sha256_file_matches_hashlib(sample: Path) -> None:
    assert sha256_file(sample) == hashlib.sha256(sample.read_bytes()).hexdigest()


def test_sha256_of_a_large_file_is_read_in_chunks(tmp_path: Path) -> None:
    big = tmp_path / "big.bin"
    big.write_bytes(b"\x00" * (3 * 1024 * 1024 + 7))  # more than one chunk, not a multiple
    assert sha256_file(big) == hashlib.sha256(big.read_bytes()).hexdigest()


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("sha256:" + "ab" * 32, "ab" * 32),
        ("AB" * 32, "ab" * 32),
        ("SHA256 = " + "cd" * 32, "cd" * 32),
        ("sha256:not-hex", None),
        ("ab" * 20, None),  # too short to be a sha256
        ("", None),
        (None, None),
    ],
)
def test_normalize_digest(raw: str | None, expected: str | None) -> None:
    assert normalize_digest(raw) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("ab" * 32 + "  UsageMonitorForCopilot.exe\n", "ab" * 32),
        ("ab" * 32 + " *UsageMonitorForCodex.exe", "ab" * 32),
        ("AB" * 32 + "\n", "ab" * 32),
        ("\n\n" + "cd" * 32 + "\n", "cd" * 32),
        ("# generated by the release workflow\n" + "ef" * 32 + "  m.exe\n", "ef" * 32),
        ("no digest in here\n", None),
        ("", None),
    ],
)
def test_parse_sidecar(text: str, expected: str | None) -> None:
    assert parse_sidecar(text) == expected


def test_verify_digest_accepts_both_spellings(sample: Path) -> None:
    digest = sha256_file(sample)
    assert verify_digest(sample, digest) is True
    assert verify_digest(sample, f"sha256:{digest}") is True
    assert verify_digest(sample, digest.upper()) is True


def test_verify_digest_rejects_a_mismatch_or_a_missing_expectation(sample: Path) -> None:
    assert verify_digest(sample, "00" * 32) is False
    assert verify_digest(sample, None) is False
    assert verify_digest(sample, "garbage") is False


def test_verify_digest_of_a_missing_file_is_false(tmp_path: Path) -> None:
    assert verify_digest(tmp_path / "nope.exe", "ab" * 32) is False


@pytest.mark.skipif(sys.platform != "win32" or not KERNEL32.exists(), reason="needs a signed Windows DLL")
def test_authenticode_reports_a_signed_system_dll() -> None:
    assert authenticode_status(KERNEL32) == "signed_valid"


def test_authenticode_reports_an_unsigned_file(sample: Path) -> None:
    status = authenticode_status(sample)
    assert status == "not_signed" if sys.platform == "win32" else status == "unavailable"


def test_authenticode_of_a_missing_file_is_unavailable(tmp_path: Path) -> None:
    assert authenticode_status(tmp_path / "gone.exe") == "unavailable"


def test_integrity_result_summaries() -> None:
    verified = IntegrityResult(hash_verified=True, source="digest", signature="not_signed")
    assert "matches" in verified.summary() and "GitHub API digest" in verified.summary()
    assert verified.unverifiable is False

    sidecar = IntegrityResult(hash_verified=False, source="sidecar", signature="signed_valid")
    assert "DOES NOT MATCH" in sidecar.summary() and ".sha256 sidecar" in sidecar.summary()

    nothing = IntegrityResult(hash_verified=False, source="none", signature="unavailable")
    assert nothing.unverifiable is True
    assert "unverifiable" in nothing.summary()
    assert nothing.to_dict() == {
        "hash_verified": False,
        "source": "none",
        "signature": "unavailable",
        "expected": None,
        "actual": None,
    }
