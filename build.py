"""Build ``dist\\UsageMonitorManager.exe`` with PyInstaller.

Same pipeline as the monitors (PLAN.md section 4.2): a one-file, no-console
executable carrying a generated ``version_info.py`` so that the PE
``ProductVersion`` matches ``__version__`` and the manager can read its own
version off disk with :func:`usage_monitor_manager.versions.exe_version` -
exactly the way it reads the monitors'.

Usage::

    .venv\\Scripts\\python build.py [--clean] [--no-icon]

Steps: generate the icon, generate ``version_info.py``, run PyInstaller on
``usage_monitor_manager.spec``, then print the resulting file with its sha256.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from usage_monitor_manager import __version__  # noqa: E402 - after the path setup

SPEC = REPO_ROOT / "usage_monitor_manager.spec"
DIST = REPO_ROOT / "dist"
BUILD = REPO_ROOT / "build"
VERSION_INFO = REPO_ROOT / "version_info.py"
ICON = REPO_ROOT / "assets" / "UsageMonitorManager.ico"
EXE_NAME = "UsageMonitorManager.exe"

VERSION_INFO_TEMPLATE = """# Generated by build.py - do not edit.
# PE version resource for {exe_name}, version {version}.
VSVersionInfo(
    ffi=FixedFileInfo(
        filevers=({a}, {b}, {c}, 0),
        prodvers=({a}, {b}, {c}, 0),
        mask=0x3F,
        flags=0x0,
        OS=0x40004,
        fileType=0x1,
        subtype=0x0,
        date=(0, 0),
    ),
    kids=[
        StringFileInfo(
            [
                StringTable(
                    "040904B0",
                    [
                        StringStruct("CompanyName", "hybrid2102"),
                        StringStruct("FileDescription", "Usage Monitor Manager"),
                        StringStruct("FileVersion", "{version}"),
                        StringStruct("InternalName", "UsageMonitorManager"),
                        StringStruct("LegalCopyright", "MIT"),
                        StringStruct("OriginalFilename", "{exe_name}"),
                        StringStruct("ProductName", "Usage Monitor Manager"),
                        StringStruct("ProductVersion", "{version}"),
                    ],
                )
            ]
        ),
        VarFileInfo([VarStruct("Translation", [0x0409, 1200])]),
    ],
)
"""


def version_tuple(version: str) -> tuple[int, int, int]:
    parts = (version.split("+")[0].split("-")[0].split(".") + ["0", "0", "0"])[:3]
    numbers: list[int] = []
    for part in parts:
        digits = "".join(character for character in part if character.isdigit())
        numbers.append(int(digits) if digits else 0)
    return (numbers[0], numbers[1], numbers[2])


def write_version_info(version: str = __version__, path: Path = VERSION_INFO) -> Path:
    """Write ``version_info.py`` for PyInstaller's ``--version-file``."""
    major, minor, patch = version_tuple(version)
    path.write_text(
        VERSION_INFO_TEMPLATE.format(version=version, a=major, b=minor, c=patch, exe_name=EXE_NAME),
        encoding="utf-8",
    )
    return path


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build UsageMonitorManager.exe")
    parser.add_argument("--clean", action="store_true", help="remove build/ and dist/ first")
    parser.add_argument("--no-icon", action="store_true", help="skip regenerating the .ico")
    parser.add_argument("--sha", action="store_true", help="also write <exe>.sha256 next to the executable")
    args = parser.parse_args(argv)

    if args.clean:
        for directory in (BUILD, DIST):
            shutil.rmtree(directory, ignore_errors=True)

    if not args.no_icon:
        from tools.generate_icon import generate

        generate(ICON)
        print(f"icona: {ICON}")

    info = write_version_info()
    print(f"version_info: {info} ({__version__})")

    command = [sys.executable, "-m", "PyInstaller", "--noconfirm", str(SPEC)]
    print(" ".join(command))
    result = subprocess.run(command, cwd=REPO_ROOT, check=False)  # noqa: S603 - fixed argv
    if result.returncode != 0:
        return result.returncode

    exe = DIST / EXE_NAME
    if not exe.is_file():
        print(f"build fallita: {exe} non esiste", file=sys.stderr)
        return 1
    digest = sha256(exe)
    if args.sha:
        (DIST / f"{EXE_NAME}.sha256").write_text(f"{digest}  {EXE_NAME}\n", encoding="utf-8")
    print(f"{exe}  {exe.stat().st_size / 1_048_576:.1f} MiB")
    print(f"sha256: {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
